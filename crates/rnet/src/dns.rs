//! `/etc/resolv.conf` generation.

use std::io;
use std::net::Ipv4Addr;
use std::path::Path;

use crate::model::Config;
use crate::state::Leases;

/// Render the resolver file from the static configuration and DHCP leases.
pub fn render(config: &Config, leases: &Leases) -> String {
    let mut search: Vec<String> = Vec::new();
    for domain in &config.global.search {
        push_unique(&mut search, domain.clone());
    }
    for iface in &config.interfaces {
        if let Some(lease) = leases.get(&iface.name)
            && let Some(domain) = &lease.domain
        {
            push_unique(&mut search, domain.clone());
        }
    }

    let mut servers: Vec<Ipv4Addr> = Vec::new();
    for server in &config.global.dns {
        push_unique(&mut servers, *server);
    }
    for iface in &config.interfaces {
        for server in &iface.dns {
            push_unique(&mut servers, *server);
        }
        if let Some(lease) = leases.get(&iface.name) {
            for server in &lease.dns {
                push_unique(&mut servers, *server);
            }
        }
    }

    let mut out = String::from("# Generated by rnet; do not edit.\n");
    if !search.is_empty() {
        out.push_str("search ");
        out.push_str(&search.join(" "));
        out.push('\n');
    }
    for server in servers {
        out.push_str(&format!("nameserver {server}\n"));
    }
    out
}

/// Write the resolver file atomically.
///
/// A symlink is refused: replacing it would silently break a resolver managed
/// by the distribution or another tool. The operator can disable
/// `manage-resolv-conf` or point the symlink at a file rnet owns.
pub fn write(path: &Path, config: &Config, leases: &Leases) -> io::Result<()> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                format!("{} is a symlink; refusing to replace it", path.display()),
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    let content = render(config, leases);
    let temporary = path.with_extension("rnet.tmp");
    match std::fs::write(&temporary, &content).and_then(|()| std::fs::rename(&temporary, path)) {
        Ok(()) => Ok(()),
        // An initramfs can be close enough to full that a second inode does
        // not fit while the existing resolver file still does. A direct
        // truncate/write is not atomic, but a stale resolver is worse than a
        // non-atomic one.
        Err(error) if error.raw_os_error() == Some(libc::ENOSPC) => {
            let _ = std::fs::remove_file(&temporary);
            std::fs::write(path, content)
        }
        Err(error) => {
            let _ = std::fs::remove_file(&temporary);
            Err(error)
        }
    }
}

fn push_unique<T: PartialEq>(values: &mut Vec<T>, value: T) {
    if !values.contains(&value) {
        values.push(value);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dhcp::lease::Lease;
    use crate::model::{Interface, InterfaceKind};

    fn lease(domain: &str, dns: Ipv4Addr) -> Lease {
        Lease {
            address: Ipv4Addr::new(192, 168, 1, 50),
            prefix: 24,
            server: Ipv4Addr::new(192, 168, 1, 1),
            lease_time: 3600,
            t1: 1800,
            t2: 3150,
            routers: Vec::new(),
            dns: vec![dns],
            domain: Some(domain.to_string()),
            routes: Vec::new(),
        }
    }

    #[test]
    fn render_merges_and_deduplicates() {
        let mut config = Config::default();
        config.global.dns = vec![Ipv4Addr::new(1, 1, 1, 1)];
        config.global.search = vec!["lan".to_string()];
        let mut iface = Interface::new("eth0".to_string(), InterfaceKind::Ethernet);
        iface.dns = vec![Ipv4Addr::new(1, 1, 1, 1), Ipv4Addr::new(9, 9, 9, 9)];
        config.interfaces.push(iface);
        let mut leases = Leases::new();
        leases.insert(
            "eth0".to_string(),
            lease("dhcp.lan", Ipv4Addr::new(9, 9, 9, 9)),
        );
        let text = render(&config, &leases);
        assert!(text.contains("search lan dhcp.lan"));
        assert_eq!(text.matches("nameserver 1.1.1.1").count(), 1);
        assert_eq!(text.matches("nameserver 9.9.9.9").count(), 1);
        assert_eq!(text.matches("nameserver").count(), 2);
    }

    #[test]
    fn write_replaces_a_regular_file() {
        let root = std::env::temp_dir().join(format!("rnet-dns-write-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).expect("temp");
        let path = root.join("resolv.conf");
        std::fs::write(&path, "old\n").expect("old");
        let config = Config::default();
        let leases = Leases::new();
        write(&path, &config, &leases).expect("write");
        let text = std::fs::read_to_string(&path).expect("read");
        assert!(text.starts_with("# Generated by rnet"));
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn symlink_is_refused() {
        let root = std::env::temp_dir().join(format!("rnet-dns-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).expect("temp");
        let target = root.join("target");
        std::fs::write(&target, "old\n").expect("target");
        let link = root.join("resolv.conf");
        std::os::unix::fs::symlink(&target, &link).expect("symlink");
        let config = Config::default();
        let leases = Leases::new();
        assert!(write(&link, &config, &leases).is_err());
        let _ = std::fs::remove_dir_all(root);
    }
}
